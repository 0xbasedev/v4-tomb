// Regenerates src/lib/abis/protocol.ts from the Foundry build output.
//   forge build (in ../contracts), then: pnpm gen:abis
// Only the functions the interface calls are kept, plus every custom error so a
// revert can be named in a toast. Add a function name here when the UI needs it.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const out = (name) => JSON.parse(readFileSync(new URL(`../../contracts/out/${name}.sol/${name}.json`, import.meta.url), "utf8")).abi;

const PICK = {
  treasury: ["Treasury", ["epoch", "nextEpochPoint", "PERIOD", "startTime", "getPegPrice", "getPegUpdatedPrice", "getPegCirculatingSupply", "getExpansionAmount", "pegPriceOne", "pegPriceCeiling", "daoFund", "devFund", "daoFundSharedPercent", "devFundSharedPercent", "maxSupplyExpansionPercent", "operator"]],
  masonry: ["Masonry", ["share", "peg", "totalSupply", "balanceOf", "earned", "canWithdraw", "canClaimReward", "members", "withdrawLockupEpochs", "rewardLockupEpochs", "operator", "stake", "withdraw", "claimReward", "exit"]],
  pegDefenseHook: ["PegDefenseHook", ["currentTaxRate", "targetTaxRate", "pendingTaxDecrease", "currentTaxPrice", "taxRate", "autoCalculateTax", "feeRecipient", "burnThreshold", "pendingTaxBurn", "pendingTaxRoute", "deferredTaxStatus", "totalTaxAssessed", "totalTaxBurned", "totalTaxRouted", "lastTick", "priceFromTick", "bound", "pegIsCurrency0", "pegTick", "bandTicks", "expansionFee", "baseFee", "contractionFee", "deepContractionFee", "MAX_TAX_BPS", "TAX_RECOVERY_PERIOD", "owner", "operator", "trustees", "pokeTaxRate", "settleDeferredTax"]],
  shareBuybackHook: ["ShareBuybackHook", ["pendingQuote", "totalQuoteAssessed", "totalQuoteConverted", "totalPegBurned", "buybackStatus", "taxEnabled", "bound", "quote", "twapWindow", "owner", "operator", "trustees", "executeBuyback"]],
  lpOnlyHook: ["LpOnlyHook", ["bound", "tokenA", "tokenB"]],
  genesisRewardPool: ["GenesisRewardPool", ["TOTAL_REWARDS", "RUNNING_TIME", "poolStartTime", "poolEndTime", "poolInfo", "userInfo", "pendingPeg", "totalAllocPoint", "operator", "deposit", "withdraw", "emergencyWithdraw"]],
  pegFarm: ["PegFarm", ["TOTAL_REWARDS", "poolStartTime", "epochEndTimes", "poolInfo", "userInfo", "pendingPeg", "totalAllocPoint", "operator", "deposit", "withdraw", "emergencyWithdraw"]],
  shareFarm: ["ShareFarm", ["TOTAL_REWARDS", "RUNNING_TIME", "poolStartTime", "poolEndTime", "poolInfo", "userInfo", "pendingShare", "totalAllocPoint", "operator", "deposit", "withdraw", "emergencyWithdraw"]],
  positionWrapper: ["V4PositionWrapper", ["poolId", "tickLower", "tickUpper", "wrappedBy", "wrappedLiquidity", "balanceOf", "totalSupply", "symbol", "wrap", "unwrap"]],
  miniSwapRouter: ["MiniSwapRouter", ["swapExactIn"]],
  timelock: ["Timelock", ["admin", "pendingAdmin", "delay", "MINIMUM_DELAY", "MAXIMUM_DELAY", "GRACE_PERIOD"]],
  oracle: ["Oracle", ["operator", "owner", "trustees", "getPeriod", "nextEpochPoint", "blockTimestampLast"]],
  protocolToken: ["PegToken", ["symbol", "name", "decimals", "totalSupply", "balanceOf", "allowance", "approve", "operator", "owner", "trustees"]],
};

let body = "// GENERATED by scripts/gen-abis.mjs from contracts/out — do not edit by hand.\n\n";
for (const [key, [contract, names]] of Object.entries(PICK)) {
  const abi = out(contract);
  const missing = names.filter((n) => !abi.some((e) => e.type === "function" && e.name === n));
  if (missing.length) throw new Error(`${contract} has no function ${missing.join(", ")}`);
  const picked = abi
    .filter((e) => (e.type === "function" && names.includes(e.name)) || e.type === "error")
    .map(({ type, name, inputs, outputs, stateMutability }) =>
      type === "error" ? { type, name, inputs } : { type, name, inputs, outputs, stateMutability },
    );
  body += `export const ${key}Abi = ${JSON.stringify(picked)} as const;\n\n`;
}
const target = fileURLToPath(new URL("../src/lib/abis/protocol.ts", import.meta.url));
writeFileSync(target, body);
console.log(`wrote ${target}`);
