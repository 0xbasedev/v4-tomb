#!/usr/bin/env node
// Regenerate typed ABI modules from one or more compiler ABI handoffs.
//   node scripts/gen-abis.mjs <handoff-dir> [<newer-handoff-dir> ...]
// Each handoff holds any of these folders of ABI arrays (`forge inspect <C> abi`):
//   current/ or masonry/   Masonry contracts         → <Name>.ts       (masonry<Name>Abi …)
//   bridge/                xSHARE bridge (Hyperlane) → <Name>.ts       (xTombShareBridgeAbi …)
//   shared/                interfaces                → <Name>.ts       (iERC20Abi …)
//   legacy-reference/ or core/  Old Money reference  → legacy<Name>.ts (legacyTreasuryAbi …)
// Later handoffs override earlier ones file by file, so a partial bundle can be
// layered on top of a full one. Output: src/lib/abis/masonry/ with `as const`
// arrays so viem infers argument and return types. Never hand-edit the output.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

const sources = process.argv.slice(2);
if (sources.length === 0) {
  console.error("usage: node scripts/gen-abis.mjs <handoff-dir> [<newer-handoff-dir> ...]");
  process.exit(1);
}
const out = new URL("../src/lib/abis/masonry/", import.meta.url).pathname;
mkdirSync(out, { recursive: true });

const camel = (s) => s.replace(/^I(?=[A-Z])/, "i").replace(/^XTomb/, "xTomb").replace(/^[A-Z]/, (c) => c.toLowerCase());
const groups = { current: "current", masonry: "current", bridge: "bridge", shared: "shared", "legacy-reference": "legacy", core: "legacy" };

/** name → { kind, abi, from } — later sources win. */
const modules = new Map();
for (const src of sources) {
  let origin = basename(src);
  try {
    const build = JSON.parse(readFileSync(join(src, "BUILD.json"), "utf8"));
    origin = `${build.branch ?? "?"} @ ${String(build.sourceCommit ?? "?").slice(0, 7)}`;
  } catch {
    /* older handoffs have no BUILD.json */
  }
  for (const root of [src, join(src, "abis")]) {
    for (const [dir, kind] of Object.entries(groups)) {
      let files = [];
      try {
        files = readdirSync(join(root, dir)).filter((f) => f.endsWith(".json")).sort();
      } catch {
        continue;
      }
      for (const f of files) {
        const name = basename(f, ".json");
        const abi = JSON.parse(readFileSync(join(root, dir, f), "utf8"));
        if (!Array.isArray(abi)) throw new Error(`${dir}/${f}: expected an ABI array`);
        modules.set(kind === "legacy" ? `legacy${name}` : name, { kind, abi, from: `${origin} · ${dir}/${f}` });
      }
    }
  }
}

const index = [];
for (const [file, { kind, abi, from }] of [...modules].sort(([a], [b]) => a.localeCompare(b))) {
  const id = kind === "legacy" ? `${file}Abi` : `${camel(file)}Abi`;
  const note =
    kind === "legacy"
      ? "Old Money reference interface: study only, never wired to xTOMB writes."
      : kind === "bridge"
        ? "xSHARE bridge (Hyperlane). Actions stay disabled until a verified deployment is published."
        : "Masonry protocol interface.";
  writeFileSync(join(out, `${file}.ts`), `// Generated by scripts/gen-abis.mjs from ${from} — do not edit.\n// ${note}\nexport const ${id} = ${JSON.stringify(abi)} as const;\n`);
  index.push(`export { ${id} } from "./${file}";`);
}
writeFileSync(join(out, "index.ts"), `// Generated by scripts/gen-abis.mjs — do not edit.\n${index.join("\n")}\n`);
console.log(`wrote ${index.length} ABI modules to src/lib/abis/masonry/`);
